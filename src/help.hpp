    cout << "bang " << version << endl;
    cout << R"(
The greatest automation toolkit ever.

Usage:
  bang [options] <scriptname> [args...]

Arguments:
  <scriptname>   Path to the script to run. Scripts are in .sh format and are stored in ~/.config/bang/ or .bang (in any directory)
  [args...]      Arguments passed through to the script

Options:
  -h, --help     Show this help message and exit
  --ci           Runs in CI mode. Should not be used except within something like a GitHub action, or if you
                 really, really want to test to see if it works.
  --version      Show version information and exit

Examples:
  bang run
  bang compile hello.cc
  bang --ci
)";
